window.WN = window.WN || {};

WN.uiLang = function () {
  try { return localStorage.getItem('wn_ui_lang') === 'en' ? 'en' : 'tr'; } catch (e) { return 'tr'; }
};

WN.t = function (key, params) {
  const dict = I18N[WN.uiLang()];
  let text = key in dict ? dict[key] : key;
  if (typeof text === 'string' && params) {
    for (const p in params) text = text.split('{' + p + '}').join(params[p]);
  }
  return text;
};

WN.applyI18n = function () {
  document.documentElement.lang = WN.uiLang();
  document.querySelectorAll('[data-i18n]').forEach(el => {
    let params = null;
    try { params = el.dataset.i18nParams ? JSON.parse(el.dataset.i18nParams) : null; } catch (e) { }
    el.textContent = WN.t(el.dataset.i18n, params);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => { el.placeholder = WN.t(el.dataset.i18nPlaceholder); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = WN.t(el.dataset.i18nTitle); });
};
